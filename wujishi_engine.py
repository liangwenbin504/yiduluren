"""五吉时引擎（2026-08-20）：要诀"取元辰时，五吉时内己巳为优；取武财时，五吉时内甲辰最善"——
五吉时=时柱斗首化气为吉星（元辰/武财/廉贞）之时辰。五鼠遁时干→化气五行→(山家,化气)查斗首星曜表。
出处：张九仪《仪度六壬选日要诀》"五、讲得明白讲得的确"两例；斗首星曜表=engine/douhou_analyzer 权威口径。"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

_ZHI = '子丑寅卯辰巳午未申酉戌亥'
_TEN = '甲乙丙丁戊己庚辛壬癸'
# 斗首星曜表：(山家五行, 化气五行) → 星曜（同 douhou_analyzer.DOUSHOU_STAR_MAP）
_STAR = {
    ('土', '土'): '元辰', ('土', '金'): '廉贞', ('土', '水'): '武财', ('土', '木'): '破鬼', ('土', '火'): '贪官',
    ('金', '金'): '元辰', ('金', '水'): '廉贞', ('金', '木'): '武财', ('金', '火'): '破鬼', ('金', '土'): '贪官',
    ('水', '水'): '元辰', ('水', '木'): '廉贞', ('水', '火'): '武财', ('水', '土'): '破鬼', ('水', '金'): '贪官',
    ('木', '木'): '元辰', ('木', '火'): '廉贞', ('木', '土'): '武财', ('木', '金'): '破鬼', ('木', '水'): '贪官',
    ('火', '火'): '元辰', ('火', '土'): '廉贞', ('火', '金'): '武财', ('火', '水'): '破鬼', ('火', '木'): '贪官',
}
_WUZI = {'甲': '甲', '己': '甲', '乙': '丙', '庚': '丙', '丙': '戊', '辛': '戊',
         '丁': '庚', '壬': '庚', '戊': '壬', '癸': '壬'}
_HUQI = {'甲': '土', '己': '土', '乙': '金', '庚': '金', '丙': '水', '辛': '水',
         '丁': '木', '壬': '木', '戊': '火', '癸': '火'}
_JI = ('元辰', '武财', '廉贞')


def wujishi(ri_gan: str, shan_wx: str) -> dict:
    """12 时辰时柱斗首星曜 → 吉时（元辰/武财/廉贞）清单。"""
    if ri_gan not in _WUZI or shan_wx not in ('金', '木', '水', '火', '土'):
        return {'全部': [], '吉时': [], '叙事': ''}
    qs = _WUZI[ri_gan]
    all_rows = []
    ji_rows = []
    for n, zhi in enumerate(_ZHI):
        gan = _TEN[(_TEN.index(qs) + n) % 10]
        hq = _HUQI[gan]
        star = _STAR.get((shan_wx, hq), '')
        row = {'时': zhi + '时', '时柱': gan + zhi, '化气': hq, '星曜': star}
        all_rows.append(row)
        if star in _JI:
            ji_rows.append(row)
    narr = ''
    if ji_rows:
        narr = ('五吉时（时柱元辰/武财/廉贞，要诀"取元辰时五吉时内己巳为优、取武财时五吉时内甲辰最善"）：'
                + '、'.join(f'{r["时"]}{r["星曜"]}' for r in ji_rows))
    return {'全部': all_rows, '吉时': ji_rows, '叙事': narr}


if __name__ == '__main__':
    import io
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
    # 用例复现：甲寅日（山家土？用例未明山——用土山测）
    r = wujishi('甲', '土')
    print(r['叙事'])
    print('吉时明细:', [(x['时'], x['时柱'], x['星曜']) for x in r['吉时']])
