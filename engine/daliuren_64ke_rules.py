def keti_tier(name: str) -> int:
    """课体三档：2=十三吉课（前）｜1=平课（中，含涉害）｜0=凶课（后）。

    憨爷 2026-09-11 拍板：「64课经只是参考，在同等分值下，十三吉课在前、
    平课在中（涉害为平）、凶课在后」。用于择日排序的**次级键**（同分裁决）。
    """
    if not name:
        return 1
    n = str(name).strip()
    stem = n[:-1] if n.endswith('课') else n
    if any(j in n or j == stem for j in _JIKE_13_NAMES):
        return 2
    if stem in _PING_OVERRIDE or n in _PING_OVERRIDE:
        return 1
    if _jixiong_for_tier(n) in _XIONG_LEVELS:
        return 0
    return 1


