def get_ke_jing_by_name(name):
    if not name: return {}
    if name in KE_JING_64: return KE_JING_64[name]
    stem = name[:-1] if name.endswith('课') else name
    if not name.endswith('课') and (name+'课') in KE_JING_64: return KE_JING_64[name+'课']
    for k,v in KE_JING_64.items():
        kstem = k[:-1] if k.endswith('课') else k
        if kstem == stem: return v
    for k,v in KE_JING_64.items():
        kstem = k[:-1] if k.endswith('课') else k
        if kstem in name or name in kstem: return v
    return {}
