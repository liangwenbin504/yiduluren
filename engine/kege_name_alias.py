"""课名归一模块（P4b · 2026-08-18）

统一"连茹"类课格的课名，消除历史别名（进连珠/退连珠/顺连茹/逆连茹/连珠课/进茹等）：
- 标准名：进连茹 / 退连茹（连茹课）；统称"连茹课"
- normalize(name) 把任意别名归一为标准名（含"X课"后缀容错）
- 引擎输出（sanchuan_kege 等）与知识库键名（liuren_64ke_v2）均已统一到标准名，
  本表仅作防御：兼容外部输入/历史数据中的杂名。
"""

# 标准名（唯一真相源）
STANDARD_NAMES = ('进连茹', '退连茹', '连茹课', '间传课', '稼穑课')

# 别名 → 标准名（含"课"后缀变体）
_ALIAS = {
    '进连珠': '进连茹', '退连珠': '退连茹',
    '顺连茹': '进连茹', '逆连茹': '退连茹',
    '进连珠课': '进连茹', '退连珠课': '退连茹',
    '顺连茹课': '进连茹', '逆连茹课': '退连茹',
    '进茹': '进连茹', '退茹': '退连茹',
    '进茹课': '进连茹', '退茹课': '退连茹',
    '连珠': '连茹课', '连珠课': '连茹课', '连茹': '连茹课',
    '联茹': '连茹课', '联珠': '连茹课',
    '进茹(气进)': '进连茹', '退茹(气退)': '退连茹',
}

# 兼容带空格/括号修饰的名字（如 "进连茹(气进)"、"顺连茹(子丑寅)"）
_PREFIX_MAP = {
    '进连茹': '进连茹', '退连茹': '退连茹',
    '进连珠': '进连茹', '退连珠': '退连茹',
    '顺连茹': '进连茹', '逆连茹': '退连茹',
    '进茹': '进连茹', '退茹': '退连茹',
    '连珠': '连茹课', '连茹': '连茹课', '联茹': '连茹课',
}


def normalize(name: str) -> str:
    """把课名归一为标准名；非连茹类课名原样返回（不误伤其他课格）。"""
    if not name:
        return name
    n = str(name).strip()
    # 精确别名
    if n in _ALIAS:
        return _ALIAS[n]
    # 前缀匹配（容忍 "进连茹(气进)"、"顺连茹·子丑寅" 等修饰）
    for prefix, std in _PREFIX_MAP.items():
        if n.startswith(prefix):
            return std
    return name


def is_lianru(name: str) -> bool:
    """判断课名是否属连茹类（含别名）。"""
    if not name:
        return False
    n = str(name)
    for k in ('进连茹', '退连茹', '连茹', '连珠', '进茹', '退茹', '联茹'):
        if k in n:
            return True
    return False
