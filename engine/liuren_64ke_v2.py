def get_keti_info(keti_name: str) -> Optional[Dict]:
    """根据课体名称获取详细信息"""
    for key, info in LIU_SHI_KETI.items():
        if key in keti_name or keti_name in key:
            return info
    return None


def get_keti_level(keti_name: str) -> Tuple[str, int, bool]:
    """
    根据课体名称获取等级和扣分

    返回: (等级名称, 扣分数, 是否大凶课)
    """
    info = get_keti_info(keti_name)
    if not info:
        return "普通课", 10, False

    level_map = {
        "上吉": (0, False),
        "大吉": (0, False),
        "中吉": (0, False),
        "小吉": (5, False),
        "吉": (5, False),
        "平": (10, False),
        "凶": (15, False),
        "小凶": (20, False),
        "中凶": (30, False),
        "大凶": (40, True),
    }

    level = info.get("吉凶", "平")
    if level in level_map:
        deduction, is_daxiong = level_map[level]
        return level, deduction, is_daxiong

    return "普通课", 10, False


def get_all_keti_names() -> List[str]:
    """获取所有课体名称"""
    return list(LIU_SHI_KETI.keys())


def get_keti_by_level(level: str) -> Dict[str, Dict]:
    """按等级获取所有课体"""
    level_map = {
        "大吉": SHANGJI_KETI,
        "中吉": ZHONGJI_KETI,
        "小吉": XIAOJI_KETI,
        "平": PING_KETI,
        "小凶": XIAOXIONG_KETI,
        "中凶": ZHONGXIONG_KETI,
        "大凶": DAXIONG_KETI
    }
    return level_map.get(level, {})



