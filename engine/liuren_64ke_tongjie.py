def get_keti_info(keti_name):
    if not keti_name:
        return None
    stem = keti_name[:-1] if keti_name.endswith('课') else keti_name
    for k, v in LIU_SHI_KETI.items():
        if k == stem or k in stem or stem in k:
            return v
    return None
