"""
六壬神煞计算模块（神煞占类化 · 2026-08-18）
====================================================
神煞口诀全部取自《大六壬指南》判词/注释原文（可验证），禁止臆造：
- 游都："太岁做游都（丙辛只向功曹上，故寅为游都）"（ZN-天时 庄公远案）
- 劫煞："中传劫煞旬丁刑克支干"（ZN-出行-一 庚申日中传巳=劫煞，申子辰劫煞在巳）
- 天马："初传天马不久即至"（郭氏案 六月天马在辰，午申戌子寅辰循环）
- 天赦："支见天赦（春三月天赦在寅）"（ZN-占讼-二）
- 血忌："血忌者，正月丑二未三寅四申五卯六酉，五月应在卯"（ZN-选举-二）
- 月建 = 月将之六合（六壬月将表：正月亥将…；寅亥合、卯戌合、辰酉合、巳申合、午未合、子丑合）
"""

ZHI_WX = {'子': '水', '丑': '土', '寅': '木', '卯': '木', '辰': '土', '巳': '火',
          '午': '火', '未': '土', '申': '金', '酉': '金', '戌': '土', '亥': '水'}

# 六合：月将 ↔ 月建
LIU_HE = {'子': '丑', '丑': '子', '寅': '亥', '亥': '寅', '卯': '戌', '戌': '卯',
          '辰': '酉', '酉': '辰', '巳': '申', '申': '巳', '午': '未', '未': '午'}


def yue_jian(yuejiang: str = '') -> str:
    """月将 → 月建（月将六合）。yuejiang 可为'申将'或'申'。"""
    yj = (yuejiang or '').replace('将', '').strip()
    return LIU_HE.get(yj, '')


def you_du(ri_gan: str = '') -> str:
    """游都（按日干）——'丙辛只向功曹上'（丙辛日游都=寅=功曹）。
    口诀：甲己日丑、乙庚日子、丙辛日寅、丁壬日巳、戊癸日申。"""
    return {'甲': '丑', '己': '丑', '乙': '子', '庚': '子', '丙': '寅', '辛': '寅',
            '丁': '巳', '壬': '巳', '戊': '申', '癸': '申'}.get(ri_gan, '')


def lu_du(ri_gan: str = '') -> str:
    """鲁都 = 游都之冲（游都对宫）。"""
    yd = you_du(ri_gan)
    chong = {'子': '午', '午': '子', '丑': '未', '未': '丑', '寅': '申', '申': '寅',
             '卯': '酉', '酉': '卯', '辰': '戌', '戌': '辰', '巳': '亥', '亥': '巳'}
    return chong.get(yd, '')


def jie_sha(ri_zhi: str = '') -> str:
    """劫煞（按日支三合）——'中传劫煞'（庚申日申子辰劫煞在巳，中传巳应）。
    口诀：申子辰在巳、寅午戌在亥、巳酉丑在寅、亥卯未在申。"""
    if ri_zhi in ('申', '子', '辰'):
        return '巳'
    if ri_zhi in ('寅', '午', '戌'):
        return '亥'
    if ri_zhi in ('巳', '酉', '丑'):
        return '寅'
    if ri_zhi in ('亥', '卯', '未'):
        return '申'
    return ''


def tian_ma(yuejiang: str = '') -> str:
    """天马（按月建）——'初传天马'（六月天马在辰：午申戌子寅辰循环）。
    口诀：正月午、二月申、三月戌、四月子、五月寅、六月辰，七月复午。"""
    jian = yue_jian(yuejiang)
    ma = {'寅': '午', '卯': '申', '辰': '戌', '巳': '子', '午': '寅', '未': '辰',
          '申': '午', '酉': '申', '戌': '戌', '亥': '子', '子': '寅', '丑': '辰'}
    return ma.get(jian, '')


def tian_she(yuejiang: str = '') -> str:
    """天赦（按月建四季）——'支见天赦（春三月天赦在寅）'（ZN-占讼-二）。
    口诀：春天赦在寅、夏天赦在午、秋天赦在申、冬天赦在子。"""
    jian = yue_jian(yuejiang)
    if jian in ('寅', '卯', '辰'):
        return '寅'
    if jian in ('巳', '午', '未'):
        return '午'
    if jian in ('申', '酉', '戌'):
        return '申'
    if jian in ('亥', '子', '丑'):
        return '子'
    return ''


def xue_ji(yuejiang: str = '') -> str:
    """血忌（按月建）——'血忌者，正月丑二未三寅四申五卯六酉，五月应在卯'（ZN-选举-二）。
    口诀：正月丑、二月未、三月寅、四月申、五月卯、六月酉、七月辰、八月戌、
    九月巳、十月亥、十一月午、十二月子。"""
    jian = yue_jian(yuejiang)
    return {'寅': '丑', '卯': '未', '辰': '寅', '巳': '申', '午': '卯', '未': '酉',
            '申': '辰', '酉': '戌', '戌': '巳', '亥': '亥', '子': '午', '丑': '子'}.get(jian, '')


def wang_shuai(wx: str = '', yuejiang: str = '') -> str:
    """五行按月建旺相休囚死——'火局旺相于春夏，死于秋冬'（ZN-兵斗-五）、
    '夏占木局枝叶正见茂盛'（ZN-仕宦-二十二）、'木逢初夏，正在荣旺之时'（ZN-仕宦-九）。
    旺=当令；相=次旺（我生者当令）；休=生我者当令；囚=克我者当令；死=我克者当令。"""
    jian = yue_jian(yuejiang)
    if jian in ('寅', '卯', '辰'):      # 春
        return {'木': '旺', '火': '相', '水': '休', '金': '囚', '土': '死'}.get(wx, '')
    if jian in ('巳', '午', '未'):      # 夏
        return {'火': '旺', '土': '相', '木': '休', '水': '囚', '金': '死'}.get(wx, '')
    if jian in ('申', '酉', '戌'):      # 秋
        return {'金': '旺', '水': '相', '土': '休', '火': '囚', '木': '死'}.get(wx, '')
    if jian in ('亥', '子', '丑'):      # 冬
        return {'水': '旺', '木': '相', '金': '休', '土': '囚', '火': '死'}.get(wx, '')
    return ''


def tai_sui(year: str = '') -> str:
    """太岁（占课年支）——'太岁发用作日破'（ZN-疾病-二）、'太岁克日，君上不喜'
    （ZN-占讼-二十一）、'朱雀乘太岁克日；太岁君也'（ZN-章奏-五）。"""
    if not year:
        return ''
    year = str(year).strip()
    if len(year) >= 2 and year[-1] in '子丑寅卯辰巳午未申酉戌亥':
        return year[-1]
    return ''


def sui_po(year: str = '') -> str:
    """岁破（太岁之冲）——'岁破为鬼'（ZN-章奏-五）、'岁破发用'（ZN-占讼-四）。"""
    ts = tai_sui(year)
    chong = {'子': '午', '午': '子', '丑': '未', '未': '丑', '寅': '申', '申': '寅',
             '卯': '酉', '酉': '卯', '辰': '戌', '戌': '辰', '巳': '亥', '亥': '巳'}
    return chong.get(ts, '')


