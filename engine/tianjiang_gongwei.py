def zhanlei_tone_note_of(jiang: str, zhanlei: str):
    """→ (tone, note, src)；无则 ('', '', '')。与 `tone_note_of` 对齐，供悬停追溯原文。"""
    r = TIANJIANG_ZHANLEI_TONE.get((str(jiang or ''), str(zhanlei or '')))
    return r if r else ('', '', '')


def zhanlei_tones_for(zhanlei: str, jiangs):
    """给定占类 ＋ 本课出现的天将集合 → 命中条目（按传入顺序、同将去重）。

    返回 [{'jiang','tone','note','src'}, ...]；供叙事层一次性取用。
    """
    out, seen = [], set()
    for j in (jiangs or []):
        j = str(j or '')
        if not j or j in seen:
            continue
        seen.add(j)
        r = TIANJIANG_ZHANLEI_TONE.get((j, str(zhanlei or '')))
        if r:
            out.append({'jiang': j, 'tone': r[0], 'note': r[1], 'src': r[2]})
    return out


