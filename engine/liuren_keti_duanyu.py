    def generate_luma_duanyu_report(self, luma_info: Dict) -> str:
        """
        生成禄马贵人到山到向报告
        
        :param luma_info: 禄马贵人信息字典
        :return: 禄马贵人断语报告
        """
        report_parts = []
        report_parts.append("【禄马贵人到山到向断语】\n")
        
        expanded_lib = self.load_expanded_library()
        luma_data = expanded_lib.get('luma_guiren_duanyu', {})
        
        for key, value in luma_info.items():
            if value:
                if key in luma_data:
                    for sub_key, sub_value in luma_data[key].items():
                        if isinstance(sub_value, dict) and sub_value.get('断语'):
                            report_parts.append(f"\n◆ {sub_key}")
                            report_parts.append(f"\n  {sub_value['断语']}")
                            if sub_value.get('详细断语', {}).get('总论'):
                                report_parts.append(f"\n  详细：{sub_value['详细断语']['总论']}")
                            if sub_value.get('发福年限'):
                                report_parts.append(f"\n  发福年限：{sub_value['发福年限']}")
                            if sub_value.get('文献依据'):
                                report_parts.append(f"\n  文献依据：{sub_value['文献依据']}")
                            report_parts.append("\n")
        
        return ''.join(report_parts)
    
    def generate_shan_xiang_report(self, shan: str, luma_info: Dict = None) -> str:
        """
        生成山向综合报告
        
        :param shan: 山名
        :param luma_info: 禄马贵人信息
        :return: 山向综合报告
        """
        report_parts = []
        
        shan_info = self.get_shan_xiang_duanyu(shan)
        
        report_parts.append(f"【{shan}综合分析】\n")
        report_parts.append(f"\n五行：{shan_info.get('五行', '未知')}")
        report_parts.append(f"\n元辰：{shan_info.get('元辰', '未知')}")
        report_parts.append(f"\n禄神：{shan_info.get('禄神', '未知')}")
        report_parts.append(f"\n驿马：{shan_info.get('驿马', '未知')}")
        report_parts.append(f"\n贵人：{', '.join(shan_info.get('贵人', []))}")
        report_parts.append(f"\n\n断语：{shan_info.get('断语', '无')}")
        
        if shan_info.get('详细断语'):
            report_parts.append("\n\n详细断语：")
            for key, value in shan_info['详细断语'].items():
                report_parts.append(f"\n  · {key}：{value}")
        
        if shan_info.get('吉年'):
            report_parts.append(f"\n\n吉年：{', '.join(shan_info['吉年'])}")
        if shan_info.get('凶年'):
            report_parts.append(f"\n凶年：{', '.join(shan_info['凶年'])}")
        
        if shan_info.get('文献依据'):
            report_parts.append(f"\n\n文献依据：{shan_info['文献依据']}")
        
        if luma_info:
            report_parts.append("\n\n")
            report_parts.append(self.generate_luma_duanyu_report(luma_info))
        
        return ''.join(report_parts)


