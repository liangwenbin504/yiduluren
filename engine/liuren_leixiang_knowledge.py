def _match_cheng_shen_yi(cheng_shen_yi: dict, jiang: str) -> str:
    """从「乘神寓意」dict 里，按当前天将别称模糊匹配出寓意（键常带条件）。"""
    if not cheng_shen_yi:
        return ''
    bies = JIANG_BIE.get(jiang, [jiang])
    for k, v in cheng_shen_yi.items():
        if any(b in k for b in bies):
            return v
    return ''


def build_leixiang(tian_jiang: dict, sanchuan: list = None, gan_shang: str = '', zhi_shang: str = '') -> list:
    """构建神将类象（精细化）：三传+干上+支上 每个天将所乘地支的类象。
    输出：属相/吉凶/所主/类象（含加临注释，如"醉人加酉"）/乘神寓意（天将乘地支）/乘神断语（天将临地支）/姓氏。
    tian_jiang 格式 {天盘支: 天将名}。
    """
    sc = sanchuan or []
    positions = []
    for i, z in enumerate(sc[:3]):
        positions.append(('初传' if i == 0 else '中传' if i == 1 else '末传', z))
    if gan_shang:
        positions.append(('干上', gan_shang))
    if zhi_shang:
        positions.append(('支上', zhi_shang))

    result = []
    seen = set()
    for pos, zhi in positions:
        if not zhi or zhi in seen:
            continue
        seen.add(zhi)
        jiang = tian_jiang.get(zhi, '')
        if not jiang:
            continue
        # 精细化类象：SHENJIANG_LEIXIANG（十二神将类象，含加临注释）
        sj_info = get_shenjiang_info(zhi) or {}
        leixiang = sj_info.get('类象', {}) or {}   # 嵌套 dict：天神/人物/身体/疾病/地理/物品/食物
        cheng_shen = _match_cheng_shen_yi(sj_info.get('乘神寓意', {}), jiang)
        # 天将类象（SHI_ER_SHEN_JIANG）：吉凶/所主/核心含义 + 乘神断语（X临地）
        sj = SHI_ER_SHEN_JIANG.get(jiang, {})
        lindi = ''
        for k, v in sj.items():
            if '临地' in k and isinstance(v, dict):
                lindi = v.get(zhi, '')
                break
        # 🔴 今译（纯展示层 · 2026-09-12）：原文一律不改，另给 *今 字段供 UI 显示。
        #   ⚠️ 今译**不得**用于吉凶判定（`tianjiang_gongwei._XIONG` 含「淫/羞」等凶键，判定须吃原文）。
        try:
            from engine.liuren_gloss import gloss as _gloss, gloss_deep as _gloss_deep
            _suozhu = sj_info.get('所主', '') or sj.get('所主', '')
            _suozhu_jin = _gloss(_suozhu)
            _dj_jin = _gloss(lindi)
            _lx_jin = _gloss_deep(leixiang)
        except Exception:
            _suozhu, _suozhu_jin, _dj_jin, _lx_jin = (
                sj_info.get('所主', '') or sj.get('所主', ''), '', '', {})
        result.append({
            '位置': pos, '地支': zhi, '天将': jiang,
            '属相': SHENGXIAO.get(zhi, ''),
            '吉凶': sj.get('吉凶', ''),
            '所主': _suozhu,
            '所主今': _suozhu_jin,
            '类象': leixiang,
            '类象今': _lx_jin,
            '乘神寓意': cheng_shen,
            '乘神断语': lindi,
            '乘神断语今': _dj_jin,
            '姓氏': sj_info.get('姓氏', ''),
        })
    return result
