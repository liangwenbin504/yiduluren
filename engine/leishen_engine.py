def _ask_llm_leishen(item: str) -> dict:
    """调用免费 glm-4-flash 询问物件 类神地支+方位断语（JSON）。

    【2026-09-06】必须显式切 glm-4-flash：GLMService() 默认 glm-5.3-flash
    强制思考 → content 返英文思维链而非地支；模板引擎已验证 glm-4-flash
    thinking=False 稳定输出目标文本。返回 {'zhi': 地支, 'direction': 方位} 或 None。
    """
    try:
        from glm_service import GLMService
        svc = GLMService()
        svc.model = 'glm-4-flash'  # 免费模型：物件→地支粗分类
        resp = svc.generate(
            messages=[{'role': 'user', 'content': _LLM_CACHE_PROMPT + item}],
            temperature=0.1, max_tokens=64, thinking=False,
        )
        if resp.get('success'):
            ans = (resp.get('content') or '').strip()
            import re as _re
            m = _re.search(r'"zhi"\s*:\s*"([子丑寅卯辰巳午未申酉戌亥])"', ans)
            zhi = m.group(1) if m else ''
            # 兜底：纯中文文本提地支字
            if not zhi:
                for ch in ans:
                    if ch in _ZHI_SET:
                        zhi = ch
                        break
            if not zhi:
                return None
            dm = _re.search(r'"direction"\s*:\s*"([^"]*)"', ans)
            direction = dm.group(1) if dm else _ZHI_DEFAULT_DIRECTION.get(zhi, '')
            return {'zhi': zhi, 'direction': direction}
    except Exception:
        pass
    return None


def _get_llm_cache_entry(item_key: str) -> dict:
    """读缓存条目：兼容旧版纯地支字符串与新版 {zhi, direction} 结构。"""
    v = (_load_llm_cache() or {}).get(item_key)
    if isinstance(v, str):
        return {'zhi': v, 'direction': _ZHI_DEFAULT_DIRECTION.get(v, '')}
    if isinstance(v, dict) and v.get('zhi'):
        return v
    return {}


def _infer_zhi_by_wx(item: str) -> str:
    """物性五行→类神地支推断（审核全失败时的兜底）：返回该五行主流地支或空。"""
    wx_hint = ''
    for kw, wx in _LLM_WX_AUDIT:
        if kw in item:
            wx_hint = wx
            break
    return {'水': '子', '火': '巳', '木': '卯', '金': '酉', '土': '辰'}.get(wx_hint, '')


def leishen_llm_fallback_cached(text: str) -> str:
    """第3层 LLM 兜底（增强版・带缓存+审核+方位联动）：
    查缓存（兼容新旧结构）→ 未命中调 LLM（地支+方位，最多3次）→
    物性五行审核（不一致重采样）→ 审核通过才固化；若 3 次全不过则用
    「物性五行→地支」推断兜底（如假牙属金→酉）。返回地支（或空）。
    """
    cache = _load_llm_cache()
    item_key = str(text or '').strip()[:20]
    entry = _get_llm_cache_entry(item_key)
    if entry.get('zhi'):
        return entry['zhi']
    zhi = ''
    entry = {}
    for _attempt in range(3):
        r = _ask_llm_leishen(item_key)
        if r and r.get('zhi') and _audit_llm_zhi(item_key, r['zhi']):
            zhi = r['zhi']
            entry = {'zhi': r['zhi'], 'direction': r.get('direction') or _ZHI_DEFAULT_DIRECTION.get(r['zhi'], '')}
            break
    if not zhi:
        # 审核 3 次全不过 → 物性五行推断兜底（保证低频物件仍有类神可用）
        zhi = _infer_zhi_by_wx(item_key)
        if zhi:
            entry = {'zhi': zhi, 'direction': _ZHI_DEFAULT_DIRECTION.get(zhi, ''),
                     'from': 'wx_infer'}
    if zhi:
        cache[item_key] = entry
        _save_llm_cache()
    return zhi


def get_llm_direction(text: str) -> str:
    """取 LLM 兜底条目中的方位断语（judge_lost_modern 拼接用）。"""
    item_key = str(text or '').strip()[:20]
    entry = _get_llm_cache_entry(item_key)
    return entry.get('direction', '')


