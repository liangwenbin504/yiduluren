def leishen_rule_fallback(text: str, force_lost: bool = False) -> str:
    """第2层：物性关键词规则兜底。静态表 miss 后按类属推断类神地支。

    【2026-09-06 防误伤】单字关键词（玉/卡/笔/钱/伞/杯/瓶/鞋）必须处于"失物语境"
    （前邻 失/丢/不/寻/找/丢/掉 或后随 不见/丢了/掉了），否则跳过——
    避免在古籍占辞（占宅/占病等）中被裸词误命中。
    【2026-09-06 寻物入口】force_lost=True 时跳过语境门槛（/api/lost/find 独立入口
    明确为失物语境，允许"助听器"等不带失字眼的裸词直接命中规则/LLM 兜底）。
    """
    t = str(text or '')
    # 失物语境标记：附近有 失/丢/掉/不/寻/找/丢/找 等
    lost_ctx = bool(force_lost) or bool(re.search(r'失|丢|掉|寻|找|不见|捡|遗', t))
    for kw, zhi, _desc in MODERN_RULE_FALLBACK:
        if kw not in t:
            continue
        if len(kw) == 1 and not lost_ctx:
            # 单字关键词缺失物语境 → 跳过（防古籍裸词误命中）
            continue
        return zhi
    return ''


def leishen_from_text(text: str, force_lost: bool = False) -> str:
    """从占辞/断语提取失物类神地支。
    顺序：现代表（现代物件长词优先）→ 物性规则兜底 → 六畜名 → 器物名（金/银/船…）→ 六畜表 → 断语'X为类神'句式 → LLM兜底(第3层)。
    force_lost: 寻物入口等明确失物语境置 True，允许无"失/丢/找"字眼的裸词走规则/LLM 兜底。"""
    t = str(text or '')
    # 【2026-09-06 现代分表优先】现代物件词长（如"笔记本电脑"含"电脑"），先匹配长词避免子串误配
    for item, zhi in LOST_ITEM_LEISHEN_MODERN.items():
        if item in t:
            return zhi
    # 【2026-09-06 第2层】物性规则兜底（如"电饭煲丢了"→巳、"银器"→酉）
    _rule_zhi = leishen_rule_fallback(t, force_lost)
    if _rule_zhi:
        return _rule_zhi
    for item, zhi in LOST_ITEM_LEISHEN.items():
        if item in t:
            return zhi
    for item, zhi in LIUCHU_LEISHEN.items():
        if f'失{item}' in t or f'占失{item}' in t or f'{item}不见' in t or f'失{item}' in t:
            return zhi
    # 断语句式：'X为类神' / '以X为类神' / 'X是类神'
    m = re.search(r'(以|是|属|为|系)?([子丑寅卯辰巳午未申酉戌亥])(?:为|作|是|系)?类神', t)
    if m:
        return m.group(2)
    # 【2026-09-06 第3层】LLM 兜底（静态表+规则全 miss 时；结果缓存防漂移）。
    # 防误伤：须为明显失物语境（失/丢/掉/寻/找/不见/捡/遗）才调 LLM，
    # 避免"占宅求安"等古籍占辞被 LLM 凭空映射（曾实测 占宅→辰 污染缓存）。
    # force_lost=True（寻物入口）显式放行裸词。
    if force_lost or re.search(r'失|丢|掉|寻|找|不见|捡|遗', t):
        return leishen_llm_fallback_cached(t)
    return ''


