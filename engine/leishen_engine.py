def judge_lost(leishen: str, sanchuan, gan_shang: str, zhi_shang: str,
               kong, chu_tj: str = '', zhong_tj: str = '', mo_tj: str = '',
               sike=None) -> dict:
    """失物/走失类神判法（邵公失物法，每条标出处）。

    优先级（实例验证）：受克乘虎(W3) > 乘后阴/青龙吉象 > 入传(W1) > 加日辰(W2) > 不入传(W4)。
    返回 {'end': 吉/凶/平, 'narr': 叙事, 'src': 出处}，无 leishen 返回 None。
    """
    if not leishen:
        return None
    sc = list(sanchuan or [])
    kw = set(kong or [])
    # 类神所加之地支（四课/三传中找类神为"上神"时的"下神"）——组合类象之"上下神"
    ls_xia = ''
    for k in (sike or []):
        if isinstance(k, (list, tuple)) and len(k) >= 3 and str(k[1]) == leishen:
            ls_xia = str(k[2])
            break
        if isinstance(k, dict) and str(k.get('上神', '')) == leishen:
            ls_xia = str(k.get('下神', ''))
            break
