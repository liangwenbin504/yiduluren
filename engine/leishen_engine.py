def judge_zeri_leishen(zeri_type: str, sanchuan, gan_shang: str = '', zhi_shang: str = '',
                       kong=None, chu_tj: str = '', zhong_tj: str = '', mo_tj: str = '',
                       sike=None, ri_gan: str = '', ri_zhi: str = '', tai_sui: str = '',
                       item_text: str = '', shan: str = '') -> dict:
    """择日类型 → 类神定位 → 入课吉应判定（与失物 judge_lost 同构，语义不同）。

    定位链：L1 专属表（作灶/安门/安床/提车/丧葬/祭祀/天时/终身/流年/功名/亡盗）
           → 桥接占事类神（get_category_leishen，求财/家宅/考试…）。
    丧葬/祭祀类神随山向重排：shan 参数传入后类神=山家支+向首支（2026-09-06）。

    入课吉应信号（每个主类神地支独立判）：
      · 类神受传中支所克              → 凶应（用事受制）
      · 类神入传而乘白虎/玄武        → 凶应（忌将临用）
      · 类神加日辰而临旬空            → 凶应（应期落空）
      · 类神临长生之地                → 吉应（得气得养）
      · 类神入传（乘青贵六合常后阴  → 强吉应）
      · 类神加日辰不落空亡            → 吉应
      · 类神临墓库                    → 平（事有迟滞收藏）
      · 类神不入课传                  → 平（用事之应不显，需看整体课吉）
                                    ★ 与失物"不入传=凶"不同：择日不入传≠凶，只减应验
    特殊情况：择日类型=亡盗（寻物访贼）→ 直接复用 judge_lost_modern 失物判法。
    多类神并存时取最高信号：凶 > 吉 > 平。

    返回：
      {'zeri_type', 'category', 'leishen', 'zhi_list', 'tianjiang_table',
       'end': 吉/凶/平, 'narr', 'src'}
    """
    WX = {'子': '水', '丑': '土', '寅': '木', '卯': '木', '辰': '土', '巳': '火',
          '午': '火', '未': '土', '申': '金', '酉': '金', '戌': '土', '亥': '水'}
    KE = {'木': '土', '火': '金', '土': '水', '金': '木', '水': '火'}
    _WX_CS = {'木': '亥', '火': '寅', '金': '巳', '水': '申', '土': '申'}  # 长生
    _WX_MU = {'木': '未', '火': '戌', '土': '戌', '金': '丑', '水': '辰'}  # 墓库
    sc = list(sanchuan or [])
    kw = set(kong or [])

    # 【特判】亡盗/失物类 → 复用失物判法（类神随文本提取，含方位断语）
    if str(zeri_type or '') == '亡盗' and item_text:
        r = judge_lost_modern(item_text, sanchuan, gan_shang, zhi_shang, kong,
                              chu_tj, zhong_tj, mo_tj, sike)
        if r:
            r['zeri_type'] = zeri_type
            r['category'] = '亡盗'
            r.setdefault('leishen', leishen_from_text(item_text))
            return r

    # 【特判 2026-09-06】六畜占 → 畜种类神文本提取（马午/牛丑/羊未/鸡酉/犬戌/猪亥/猴申/鱼辰）
    #   复用 judge_lost 六畜章判法（§179-187 原文：类神入传/加日辰/受克乘虎/临生旺）
    if str(zeri_type or '') in ('六畜',) and item_text:
        _lcz = ''
        for _nm, _zhi in LIUCHU_LEISHEN.items():
            if _nm in item_text:
                _lcz = _zhi
                break
        if _lcz:
            r = judge_lost(_lcz, sanchuan, gan_shang, zhi_shang, kong,
                           chu_tj, zhong_tj, mo_tj, sike)
            if r:
                r['zeri_type'] = zeri_type
                r['category'] = '六畜'
                r.setdefault('leishen', _lcz)
                return r

    ls = get_category_leishen(zeri_type, ri_gan, tai_sui, '', ri_zhi, shan)
    zhi_list = ls.get('zhi_list', [])
    if not zhi_list:
        # 无固定类神地支（终身/杂占/未映射类型；丧葬/祭祀已随山向展开）→ 仅返回类神表
        _desc_ls = ls.get('desc', '')
        if _desc_ls in ('未知占事类别', ''):
            _narr_ls = f'{zeri_type}暂无类神映射，未作类神吉应调整'
        else:
            _narr_ls = f'{zeri_type}：{_desc_ls}；天将类象入课当参'
        return {'zeri_type': zeri_type, 'category': ls.get('category', zeri_type),
                'leishen': '', 'zhi_list': [], 'tianjiang_table': ls.get('tianjiang_table', {}),
                'end': '平', 'narr': _narr_ls,
                'src': 'L1专属表'}
    tj_by_pos = {'初传': chu_tj, '中传': zhong_tj, '末传': mo_tj}
    _JI_TJ = ('青龙', '贵人', '六合', '太常', '天后', '太阴')

    def _ls_xia(z):
        for k in (sike or []):
            if isinstance(k, (list, tuple)) and len(k) >= 3 and str(k[1]) == z:
                return str(k[2])
            if isinstance(k, dict) and str(k.get('上神', '')) == z:
                return str(k.get('下神', ''))
        return ''

    # 【2026-09-09 具象叙事】优先取 OX Alpha 生成的具象断语（360信号句）；
    #   未覆盖类型/信号键 → 回退旧模板（_n 末尾保留原模板，_sp 取具象句）
    _narr_specific = _load_zeri_narrative().get(str(zeri_type or ''), {})

    def _sp(signal_key, fallback):
        """具象句优先，缺失回退 fallback 模板句（fallback 为含 {z}/{pos}/{tj} 的旧模板）。"""
        s = _narr_specific.get(signal_key, '')
        return s if s else fallback

    signals = []  # (等级3凶/2吉/1平, narr, src, 类神支)
    for z in zhi_list:
        pos = leishen_in_sanchuan(z, sc)
        tj = tj_by_pos.get(pos, '') if pos else ''
        zx = _ls_xia(z)
        wx = WX.get(z, '')
        # ① 受传中支所克 → 凶应
        for kz, ktj in zip(sc, (chu_tj, zhong_tj, mo_tj)):
            if kz and wx and KE.get(WX.get(kz, ''), '') == wx:
                signals.append((3, _sp('受克凶应',
                                   f'类神{z}受传中{kz}（{WX.get(kz, "")}）所克，{zeri_type}凶应，用事受制，宜防阻滞、勿轻用'),
                                '受克凶应', z))
                break
        else:
            # ② 入传乘白虎/玄武 → 凶应（忌将临用）
            if pos and tj in ('白虎', '玄武'):
                signals.append((3, _sp('乘忌将凶应',
                                   f'类神{z}现于{pos}乘{tj}，忌将临用，{zeri_type}凶应，用事受冲，宜慎'),
                                '乘忌将凶应', z))
            # ③ 加日辰而临旬空 → 凶应
            elif (z == gan_shang or z == zhi_shang) and z in kw:
                signals.append((3, _sp('加日辰临空凶应',
                                   f'类神{z}加日辰而临旬空，{zeri_type}凶应，应期落空，宜另择吉期'), '加日辰临空凶应', z))
            # ④ 长生 → 吉应
            elif zx and wx and zx == _WX_CS.get(wx, ''):
                signals.append((2, _sp('临长生吉应',
                                   f'类神{z}加长生之地{zx}，{zeri_type}得气得养，用事顺遂'), '临长生吉应', z))
            # ⑤ 入传乘吉将 → 强吉应
            elif pos and tj in _JI_TJ:
                signals.append((2, _sp('入传乘吉将强吉应',
                                   f'类神{z}现于{pos}乘{tj}，喜用之神临课，{zeri_type}吉应显著'), '入传乘吉将强吉应', z))
            # ⑥ 入传（平将）→ 吉应
            elif pos:
                signals.append((2, _sp('入传吉应',
                                   f'类神{z}现于{pos}，{zeri_type}类神在传，用事得应'), '入传吉应', z))
            # ⑦ 加日辰不空 → 吉应
            elif z == gan_shang or z == zhi_shang:
                signals.append((2, _sp('加日辰实吉应',
                                   f'类神{z}加日辰不落空亡，{zeri_type}应验现前'), '加日辰实吉应', z))
            # ⑧ 临墓库 → 平
            elif zx and wx and zx == _WX_MU.get(wx, ''):
                signals.append((1, _sp('临墓库平应',
                                   f'类神{z}临墓库{zx}，{zeri_type}事有迟滞收藏，需待时机'), '临墓库平应', z))
            # ⑨ 不入课传 → 平（择日语义：应验不显不判凶）
            else:
                signals.append((1, _sp('不入传平应',
                                   f'类神{z}不入课传，{zeri_type}用事之应不显，宜参整体课吉'), '不入传平应', z))

    rank, narr, src, ls_z = max(signals, key=lambda s: s[0])  # 取最高信号（凶3 > 吉2 > 平1）
    end = '凶' if rank == 3 else ('吉' if rank == 2 else '平')
    if not src:
        src = 'L1/L2类神定位'
    return {'zeri_type': zeri_type, 'category': ls.get('category', zeri_type),
            'leishen': ls_z, 'zhi_list': zhi_list,
            'tianjiang_table': ls.get('tianjiang_table', {}),
            'end': end, 'narr': narr, 'src': src}


def get_xunkong(ri_gan: str, ri_zhi: str) -> list:
    """日柱干支 → 旬空二支（甲子旬→戌亥、甲戌旬→申酉…）。

    【2026-09-06 新增】供 judge_zeri_leishen 调用方计算空亡（引判据：毕法"空亡主虚，入课乘凶则凶应"）。
    旬首支 = (日支序 - 日干序) % 12（时支自旬首顺数 10/11 位为空亡）。
    """
    GAN = '甲乙丙丁戊己庚辛壬癸'
    ZHI = '子丑寅卯辰巳午未申酉戌亥'
    if not ri_gan or not ri_zhi or ri_gan not in GAN or ri_zhi not in ZHI:
        return []
    xun_zhi = (ZHI.index(ri_zhi) - GAN.index(ri_gan) + 12) % 12
    return [ZHI[(xun_zhi + 10) % 12], ZHI[(xun_zhi + 11) % 12]]


