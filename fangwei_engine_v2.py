def huanjing_of(leishen: str, xia: str, tj: str) -> str:
    """环境类象：类神×下神/天将→场所。"""
    if (leishen, tj) in HUANJING_XIANG:
        return HUANJING_XIANG[(leishen, tj)]
    if (leishen, xia) in HUANJING_XIANG:
        return HUANJING_XIANG[(leishen, xia)]
    return ''


