def fangwei_of_zhi(zhi: str) -> str:
    """地支→方位。"""
    return ZHI_FANGWEI.get(zhi, '')


def leishen_jia_fang(leishen: str, sike, tdp, sanchuan) -> dict:
    """失物方向判法（类神所加地盘支→方位）。
    口径（liuren_case_kb 吴稼云）：类神已见（在课传）则类神所临处为方向；
    类神未见则以初传为方向类神（§200 卯不见传，初传寅加辰=东南，果于东南寻见）。
    返回 {'fang': 方位, 'zhi': 所加支, 'mode': '类神加临'/'初传定向', 'src': 出处}。"""
    sc = list(sanchuan or [])
    # 类神所加地盘（四课上下神中找；再查天地盘）
    jia = ''
    for k in (sike or []):
        if isinstance(k, (list, tuple)) and len(k) >= 3 and str(k[1]) == leishen:
            _x = str(k[2])
            if _x in ZHI_FANGWEI:   # 下神须为地支方为"加临"（§184 伏吟课2未加未；课1未加干不算）
                jia = _x
                break
        elif isinstance(k, dict) and str(k.get('上神', '')) == leishen:
            _x = str(k.get('下神', ''))
            if _x in ZHI_FANGWEI:
                jia = _x
                break
    if jia and jia in ZHI_FANGWEI:
        return {'fang': ZHI_FANGWEI[jia], 'zhi': jia, 'mode': '类神加临',
                'src': '§199"酉为类神作勾临午…物在南方炉灶前"; §127"未加卯…往东方寻之必见"; §184"未为羊…故在西南"'}
    # 类神在天盘（课传外）所加地盘
    if tdp and isinstance(tdp, dict):
        for di, tian in tdp.items():
            if tian == leishen and di in ZHI_FANGWEI:
                return {'fang': ZHI_FANGWEI[di], 'zhi': di, 'mode': '类神加临(天盘)',
                        'src': '§200"今日卯为类神，加巳，是在地户东南上也"'}
    # 类神未见 → 初传所加地盘为方向（吴稼云）
    if sc:
        chu = sc[0]
        jia2 = ''
        for k in (sike or []):
            if isinstance(k, (list, tuple)) and len(k) >= 3 and str(k[1]) == chu:
                jia2 = str(k[2])
                break
            if isinstance(k, dict) and str(k.get('上神', '')) == chu:
                jia2 = str(k.get('下神', ''))
                break
        if not jia2 and tdp and isinstance(tdp, dict):
            for di, tian in tdp.items():
                if tian == chu and di in ZHI_FANGWEI:
                    jia2 = di
                    break
        if jia2 in ZHI_FANGWEI:
            return {'fang': ZHI_FANGWEI[jia2], 'zhi': jia2, 'mode': '类神未见初传定向',
                    'src': '吴稼云"类神未见，则以初传为方向类神"; §200 初传寅加辰=东南，果于东南上寻见'}
    return {'fang': '', 'zhi': '', 'mode': '', 'src': ''}


def yima_fangwei(ri_zhi: str) -> dict:
    """驿马方位（出行/行人去向）：驿马支本身方位（§153 寅马→东北）。"""
    _MA = {'申': '寅', '子': '寅', '辰': '寅', '寅': '申', '午': '申', '戌': '申',
           '巳': '亥', '酉': '亥', '丑': '亥', '亥': '巳', '卯': '巳', '未': '巳'}
    ma = _MA.get(ri_zhi, '')
    if not ma:
        return {'fang': '', 'zhi': '', 'src': ''}
    return {'fang': ZHI_FANGWEI.get(ma, ''), 'zhi': ma,
            'src': '§出行访谒11·153"寅马加亥…行动于东北者"——寅=东北，果自乡里从东北过西北'}


def xuanwu_fangwei(xuanwu_zhi: str) -> str:
    """玄武所临方位（贼盗方向，§641"酉为玄武临丑，其贼往东南方盗得他人财"）。"""
    return ZHI_FANGWEI.get(xuanwu_zhi, '')


# ══════════════════════════════════════════════════════════════
# 四、道里数法（远近）
# ══════════════════════════════════════════════════════════════

def daoli_zhi_sum(*zhis) -> dict:
    """多支洛书数求和（§017"巳四、子九，并成十三年"——年数/里数/日数通用）。"""
    s = 0
    parts = []
    for z in zhis:
        if z in ZHI_SUZHI:
            s += ZHI_SUZHI[z]
            parts.append(f'{z}{ZHI_SUZHI[z]}')
    return {'sum': s, 'parts': '、'.join(parts),
            'src': '§017"巳四、子九，并成十三年"; §085"丑八酉六"; §640"午九酉六"'}


def daoli_wx_sum(*wx) -> dict:
    """五行数求和（§200"寅卯木三数，辰五数，共八，故初八日内也"——木3+土5=8）。"""
    s = 0
    parts = []
    for w in wx:
        if w in WX_SUZHI:
            s += WX_SUZHI[w]
            parts.append(f'{w}{WX_SUZHI[w]}')
    return {'sum': s, 'parts': '、'.join(parts),
            'src': '§亡盗15·200"寅、卯木三数，辰五数，共八，故初八日内也"'}


