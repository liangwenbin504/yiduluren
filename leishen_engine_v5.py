def leishen_from_text(text: str) -> str:
    """从占辞/断语提取失物类神地支。
    顺序：失物速查表（银/船/金环…）→ 六畜表 → 断语'X为类神'句式。"""
    t = str(text or '')
    for item, zhi in LOST_ITEM_LEISHEN.items():
        if item in t:
            return zhi
    for item, zhi in LIUCHU_LEISHEN.items():
        if f'失{item}' in t or f'{item}不见' in t or f'占失{item}' in t:
            return zhi
    # 断语句式：'X为类神' / '以X为类神' / 'X是类神'
    m = re.search(r'([子丑寅卯辰巳午未申酉戌亥])(?:为|作|是|系)?类神|以([子丑寅卯辰巳午未申酉戌亥])为类神', t)
    if m:
        return m.group(1) or m.group(2)
    return ''


def is_liuchu_item(text: str) -> bool:
    """占物是否为六畜（活物）。含六畜字即真；银/金/船/婢/奴/度牒等为器物/人。"""
    t = str(text or '')
    for w in LIUCHU_WORDS:
        if f'失{w}' in t or f'{w}不见' in t or f'占失{w}' in t:
            return True
    return False


def leishen_in_sanchuan(leishen: str, sanchuan) -> str:
    """类神在三传的位置（初/中/末），不在返回''。"""
    sc = list(sanchuan or [])
    for i, z in enumerate(sc):
        if z == leishen:
            return ('初传', '中传', '末传')[i]
    return ''


