# 主函数：射覆综合判物
# ══════════════════════════════════════════════════════════════
def shefu(ri_gan: str, ri_zhi: str, sanchuan, tianjiang_list,
          kong, sike, keti: str = '', yuejiang: str = '',
          wangshuai: str = '') -> dict:
    """射覆判物。返回 {有物, 物类, 形质, 颜色, 死活, 新旧, 虚实, 数目, 左右, 覆仰, 五味, 细节, 叙事, 出处}。"""
    ys = shefu_yongshen(ri_gan, sike, sanchuan)
    ys_zhi = ys['用神']
    chu = ys['初传']
    zhi_shang = ys['辰上神']
    gan_shang = ys['日上神']
    sc = list(sanchuan or [])
    tj = list(tianjiang_list or [])
    chu_tj = tj[0] if tj else ''
    ys_tj = ''
    if ys_zhi == chu:
        ys_tj = chu_tj
    ys_wx = WX.get(ys_zhi, '')
    zs_wx = WX.get(zhi_shang, '')
    srcs = [ys['src']]

    # ① 有无：发用乘天空且落空亡→无物；天空/旬空临日辰→无物（诀十五原文）
    kw = set(kong or [])
    you_wu = {'有物': True, 'narr': ''}
    if chu_tj == '天空' and chu in kw:
        you_wu = {'有物': False, 'narr': f'发用{chu}乘天空又落旬空，覆主无物'}
        srcs.append('《射覆无移口鉴》"凡发用见天空，更落空亡，主射覆无物"（例一：寅加酉为用，将得天空下坐旬空，覆射主无物）')
    elif chu_tj == '天空' and (chu == gan_shang or chu == zhi_shang):
        you_wu = {'有物': False, 'narr': f'发用{chu}乘天空临日辰，覆主无物'}
        srcs.append('"即不见天空发用，但见诸空亡临日辰上者，亦主无物"')

    # ② 物类（用神五行 base + 日辰上神细化 5×5 + 十二神类象 + 天将类神 + 旺衰细化）
    wulei_parts = []
    if ys_wx:
        wulei_parts.append(WUXING_BASE.get(ys_wx, ''))
        srcs.append('《射覆无移口鉴》"用起' + ys_wx + '神，主' + WUXING_BASE.get(ys_wx, '') + '"')
        if zs_wx and (ys_wx, zs_wx) in WUXING_JIAN:
            wulei_parts.append('日辰上见' + zs_wx + '为' + WUXING_JIAN[(ys_wx, zs_wx)])
            srcs.append('"日辰上见' + zs_wx + '，为' + WUXING_JIAN[(ys_wx, zs_wx)] + '"')
    if ys_zhi in SHIER_SHEN:
        wulei_parts.append(SHIER_SHEN[ys_zhi])
        srcs.append('《射覆无移口鉴》十二神类象：' + ys_zhi + '主' + SHIER_SHEN[ys_zhi])
    if ys_tj in TIANJIANG_LEI:
        wulei_parts.append(TIANJIANG_LEI[ys_tj])
        srcs.append('十二天将类神：' + ys_tj + '主' + TIANJIANG_LEI[ys_tj])
    if (ys_tj, ys_zhi) in TIANGUAN_CHEN:
        wulei_parts.append(TIANGUAN_CHEN[(ys_tj, ys_zhi)])
        srcs.append('《苗公射覆鬼撮脚》天官加十二辰：' + ys_tj + '加' + ys_zhi + '主' + TIANGUAN_CHEN[(ys_tj, ys_zhi)])
    if (ys_wx, wangshuai) in WANG_XIANG_WU:
        wulei_parts.append(WANG_XIANG_WU[(ys_wx, wangshuai)])
        srcs.append('旺衰物类：' + ys_wx + wangshuai + '为' + WANG_XIANG_WU[(ys_wx, wangshuai)])

    # ③ 形质（五行形 + 孟仲季 + 天乙圆方）
    xing = WX_XING.get(ys_wx, '')
    if ys_zhi in MENG:
        xing += '；四孟主圆、有角'
    elif ys_zhi in ZHONG:
        xing += '；四仲主方、有口'
    elif ys_zhi in JI:
        xing += '；四季主长、有尖'

    # ④ 虚实（诀十：水实火虚；天空旬空入传→中空）
    xushi = ''
    if ys_wx == '水':
        xushi = '中实（坎中满）'
    elif ys_wx == '火':
        xushi = '中虚（离中虚）'
    if ys_wx == '火' and zs_wx == '水' or (ys_wx == '水' and zs_wx == '火'):
        xushi = '半虚半实'
    if (chu_tj == '天空' or chu in kw) and chu in sc:
        xushi += '；天空旬空入传，中空之物'

    # ⑤ 死活（诀十一：支上旺相相生=活、囚死=死；鬼撮脚：孟活仲塑画季死）
    sihuo = ''
    if ys_zhi in MENG:
        sihuo = '活物（四孟为活物）'
