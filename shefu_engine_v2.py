    # ⑥ 新旧（诀二四：旺相加日辰=新鲜、休囚=故旧）
    xinjiu = '新鲜物' if wangshuai in ('旺', '相') else ('故旧物' if wangshuai in ('休', '囚', '死') else '')

    # ⑦ 数目（诀十四：后天五行数上下相乘 + 旺倍进）
    shumu = ''
