def shefu_se(ri_gan: str, yongshen_zhi: str, wangshuai: str) -> str:
    """射覆颜色：十干本色 + 旺相休囚死从色规则。"""
    ys_wx = WX.get(yongshen_zhi, '')
    base = GAN_SE.get(ri_gan, '')
    if not ys_wx:
        return base
    if wangshuai == '旺':
        return base + f'（旺从本色{WX_SE.get(ys_wx, "")}）'
    if wangshuai == '相':
        zi = WX_SHENG.get(ys_wx, '')   # 我生=子
        return WX_SE.get(zi, base) + f'（相从子色{WX_SE.get(zi, "")}）'
    if wangshuai == '死':
        qi = WX_KE.get(ys_wx, '')      # 我克=妻
        return WX_SE.get(qi, base) + f'（死从妻色{WX_SE.get(qi, "")}）'
    if wangshuai == '囚':
        gui = WX_BEIKE.get(ys_wx, '')  # 克我=鬼
        return WX_SE.get(gui, base) + f'（囚从鬼色{WX_SE.get(gui, "")}）'
    if wangshuai == '休':
        mu = {v: k for k, v in WX_SHENG.items()}.get(ys_wx, '')  # 生我=母
        return WX_SE.get(mu, base) + f'（休从母色{WX_SE.get(mu, "")}）'
    return base


