LEISHA_SHAO_GONG = {  # 程树勋：正月起卯，顺行十二辰
    '正':'卯','二':'辰','三':'巳','四':'午','五':'未','六':'申',
    '七':'酉','八':'戌','九':'亥','十':'子','十一':'丑','十二':'寅',
}

def leisha(month_no: int) -> str:
    """雷杀（邵彦和用法＝程树勋：正月起卯顺行十二辰）。
    month_no: 1–12（正月至十二月，用事月份）
    八月 → 戌（与汪四公占家宅案「八月雷杀在戌，戌加寅，更见虎，自是雷嗔」合）"""
    keys = ['正','二','三','四','五','六','七','八','九','十','十一','十二']
    if not (1 <= month_no <= 12):
        return ''
    return LEISHA_SHAO_GONG[keys[month_no - 1]]

