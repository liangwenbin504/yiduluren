TIAN_JIANG_YIN  = frozenset(k for k, v in TIAN_JIANG_YINYANG.items() if v == '阴')

# 简写映射（课盘多用单字）
JIANG_ABBR = {'贵': '贵人', '蛇': '螣蛇', '朱': '朱雀', '合': '六合', '勾': '勾陈',
              '青': '青龙', '空': '天空', '白': '白虎', '常': '太常', '玄': '玄武',
              '阴': '太阴', '后': '天后'}

def jiang_yinyang(name: str) -> str:
    """返回 '阳' / '阴' / ''（未知）。接受全名或单字简写。"""
    n = JIANG_ABBR.get(name, name)
    return TIAN_JIANG_YINYANG.get(n, '')


